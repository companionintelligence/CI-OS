#!/bin/bash
#
# CI-OS Headless Wi-Fi Provisioning System Installer
# ==================================================
#
# This script installs and configures the headless Wi-Fi provisioning system
# on Ubuntu 24.04 LTS. It sets up:
# - Netplan configuration with NetworkManager renderer
# - Provisioning manager daemon
# - Captive portal web server
# - Systemd services
# - Required dependencies
#
# Usage: sudo ./install-provisioning.sh
#

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Script must be run as root
if [ "$EUID" -ne 0 ]; then
    echo -e "${RED}Error: This script must be run as root${NC}"
    echo "Usage: sudo $0"
    exit 1
fi

echo -e "${GREEN}==================================================${NC}"
echo -e "${GREEN}CI-OS Headless Wi-Fi Provisioning System Installer${NC}"
echo -e "${GREEN}==================================================${NC}"
echo

# Get the script directory
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
REPO_ROOT="$(dirname "$(dirname "$SCRIPT_DIR")")"

echo -e "${YELLOW}Repository root: ${REPO_ROOT}${NC}"
echo

# Check if we're on Ubuntu 24.04
if [ -f /etc/os-release ]; then
    . /etc/os-release
    if [ "$ID" != "ubuntu" ] || [ "$VERSION_ID" != "24.04" ]; then
        echo -e "${YELLOW}Warning: This script is designed for Ubuntu 24.04 LTS${NC}"
        echo -e "${YELLOW}Current OS: $PRETTY_NAME${NC}"
        read -p "Continue anyway? (y/N) " -n 1 -r
        echo
        if [[ ! $REPLY =~ ^[Yy]$ ]]; then
            exit 1
        fi
    fi
fi

echo -e "${GREEN}Step 1: Installing dependencies...${NC}"
apt-get update
apt-get install -y \
    python3 \
    python3-pip \
    python3-dbus \
    python3-gi \
    network-manager \
    dnsmasq \
    curl \
    netplan.io

# Install Python dependencies
pip3 install --break-system-packages dbus-python PyGObject || pip3 install dbus-python PyGObject

echo -e "${GREEN}✓ Dependencies installed${NC}"
echo

echo -e "${GREEN}Step 2: Configuring Netplan...${NC}"

# Backup existing netplan config
NETPLAN_DIR="/etc/netplan"
BACKUP_DIR="/etc/netplan/backup-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUP_DIR"

if ls $NETPLAN_DIR/*.yaml 1> /dev/null 2>&1; then
    echo "Backing up existing netplan configuration to $BACKUP_DIR"
    cp $NETPLAN_DIR/*.yaml "$BACKUP_DIR/" || true
fi

# Detect network interfaces
ETHERNET_IFACE=$(ip -o link show | awk -F': ' '{print $2}' | grep -E '^(eth|enp|eno)' | head -1 || echo "enp3s0")
WIFI_IFACE=$(ip -o link show | awk -F': ' '{print $2}' | grep -E '^(wlan|wlp)' | head -1 || echo "wlan0")

echo "Detected Ethernet interface: $ETHERNET_IFACE"
echo "Detected Wi-Fi interface: $WIFI_IFACE"

# Create netplan configuration
cat > "$NETPLAN_DIR/01-ci-os-provisioning.yaml" <<EOF
# CI-OS Network Configuration
# Auto-generated by provisioning installer
network:
  version: 2
  renderer: NetworkManager
  
  ethernets:
    $ETHERNET_IFACE:
      dhcp4: true
      dhcp6: true
      optional: true
  
  wifis:
    $WIFI_IFACE:
      dhcp4: true
      dhcp6: true
      optional: true
      access-points: {}
EOF

chmod 600 "$NETPLAN_DIR/01-ci-os-provisioning.yaml"

# Apply netplan configuration
echo "Applying netplan configuration..."
netplan generate
netplan apply

echo -e "${GREEN}✓ Netplan configured${NC}"
echo

echo -e "${GREEN}Step 3: Installing provisioning scripts...${NC}"

# Copy scripts to /usr/local/bin
cp "$REPO_ROOT/scripts/provisioning/provisioning_manager.py" /usr/local/bin/
cp "$REPO_ROOT/scripts/provisioning/captive_portal.py" /usr/local/bin/
chmod +x /usr/local/bin/provisioning_manager.py
chmod +x /usr/local/bin/captive_portal.py

echo -e "${GREEN}✓ Scripts installed${NC}"
echo

echo -e "${GREEN}Step 4: Creating required directories...${NC}"

mkdir -p /etc/provisioning
mkdir -p /run/provisioning
mkdir -p /var/log
mkdir -p /etc/NetworkManager/dnsmasq-shared.d

# Set permissions
chmod 755 /etc/provisioning
chmod 755 /run/provisioning

echo -e "${GREEN}✓ Directories created${NC}"
echo

echo -e "${GREEN}Step 5: Installing systemd services...${NC}"

# Copy systemd service files
cp "$REPO_ROOT/configs/systemd/device-provisioning.service" /etc/systemd/system/
cp "$REPO_ROOT/configs/systemd/captive-portal.service" /etc/systemd/system/

# Reload systemd
systemctl daemon-reload

# Enable services
systemctl enable device-provisioning.service
systemctl enable captive-portal.service

echo -e "${GREEN}✓ Systemd services installed and enabled${NC}"
echo

echo -e "${GREEN}Step 6: Configuring firewall (optional)...${NC}"

# Check if ufw is installed
if command -v ufw &> /dev/null; then
    echo "Configuring UFW firewall rules..."
    
    # Allow SSH
    ufw allow ssh
    
    # Allow HTTP for captive portal (only on local network)
    ufw allow from 10.42.0.0/24 to any port 80 proto tcp
    
    # Allow DNS and DHCP on hotspot interface
    ufw allow from 10.42.0.0/24 to any port 53 proto udp
    ufw allow from 10.42.0.0/24 to any port 67 proto udp
    
    echo -e "${GREEN}✓ Firewall rules configured${NC}"
else
    echo -e "${YELLOW}UFW not installed, skipping firewall configuration${NC}"
fi
echo

echo -e "${GREEN}Step 7: Starting services...${NC}"

# Start the provisioning service
systemctl start device-provisioning.service
systemctl start captive-portal.service

# Check status
sleep 2

if systemctl is-active --quiet device-provisioning.service; then
    echo -e "${GREEN}✓ Provisioning manager is running${NC}"
else
    echo -e "${RED}✗ Provisioning manager failed to start${NC}"
    echo "Check logs with: journalctl -u device-provisioning.service -f"
fi

if systemctl is-active --quiet captive-portal.service; then
    echo -e "${GREEN}✓ Captive portal is running${NC}"
else
    echo -e "${RED}✗ Captive portal failed to start${NC}"
    echo "Check logs with: journalctl -u captive-portal.service -f"
fi

echo
echo -e "${GREEN}==================================================${NC}"
echo -e "${GREEN}Installation Complete!${NC}"
echo -e "${GREEN}==================================================${NC}"
echo
echo "The headless Wi-Fi provisioning system has been installed."
echo
echo "Service Management:"
echo "  - Check status: systemctl status device-provisioning.service"
echo "  - View logs:    journalctl -u device-provisioning.service -f"
echo "  - Restart:      systemctl restart device-provisioning.service"
echo
echo "How it works:"
echo "  1. On boot, the device will check for Ethernet connection"
echo "  2. If no Ethernet, it will try to connect to known Wi-Fi networks"
echo "  3. If no connection, it will start a Wi-Fi hotspot: 'Setup-Device-XXXX'"
echo "  4. Connect to the hotspot and configure via the captive portal"
echo
echo "Captive Portal:"
echo "  - Hotspot SSID: Setup-Device-<MAC>"
echo "  - Portal URL:   http://10.42.0.1/config"
echo
echo -e "${YELLOW}Note: Reboot recommended to ensure all changes take effect${NC}"
echo

read -p "Would you like to reboot now? (y/N) " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
    echo "Rebooting..."
    reboot
fi
